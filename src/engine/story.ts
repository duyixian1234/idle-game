/** 播放关键节点叙事（仅首次） */
export function playMilestone(state: GameState, key: string): void {
  if (state.storyFlags[key]) return
  const text = MILESTONE_STORIES[key]
  if (!text) return
  state.storyFlags[key] = true
  pushLog(state, 'story', text)
}
